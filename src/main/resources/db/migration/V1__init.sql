CREATE TABLE dispatcher
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    status          VARCHAR(20)  NOT NULL
        CONSTRAINT chk_dispatcher_status CHECK (status IN ('AVAILABLE', 'BUSY', 'OFFLINE')),
    available_since TIMESTAMPTZ,
    version         BIGINT       NOT NULL
);

CREATE TABLE emergency_call
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caller_number          VARCHAR(16)  NOT NULL,
    type                   VARCHAR(20)  NOT NULL
        CONSTRAINT chk_call_type CHECK (type IN ('MEDICAL', 'FIRE', 'POLICE')),
    priority               VARCHAR(20)  NOT NULL
        CONSTRAINT chk_call_priority CHECK (priority IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    location               VARCHAR(255) NOT NULL,
    description            VARCHAR(1000),
    status                 VARCHAR(20)  NOT NULL
        CONSTRAINT chk_call_status CHECK (status IN ('QUEUED', 'ASSIGNED', 'CLOSED', 'ABANDONED')),
    received_at            TIMESTAMPTZ  NOT NULL,
    assigned_at            TIMESTAMPTZ,
    closed_at              TIMESTAMPTZ,
    assigned_dispatcher_id BIGINT
        CONSTRAINT fk_call_dispatcher REFERENCES dispatcher (id),
    version                BIGINT       NOT NULL
);

-- The queue and the list endpoint filter calls by status.
CREATE INDEX idx_call_status ON emergency_call (status);
-- PostgreSQL does not index foreign keys automatically.
CREATE INDEX idx_call_assigned_dispatcher ON emergency_call (assigned_dispatcher_id);
